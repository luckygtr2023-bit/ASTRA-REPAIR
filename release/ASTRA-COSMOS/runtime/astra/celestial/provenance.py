"""ASTRA Celestial - provenance and scientific confidence.

Contract: every property block carries an immutable provenance tag
stating WHERE the data came from. ASTRA distinguishes verified catalog
observations, derived quantities, engine-generated values, and
mathematical models - so downstream consumers can never mistake a
simulated placeholder for observed astronomy.

No datasets are embedded in this layer (no Gaia/JPL/SIMBAD data): this is
the receptacle architecture for a future ingestion pipeline.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum


class DataProvenance(Enum):
    """Origin class of an astronomical data value."""

    REAL_DATA = "REAL_DATA"                  # verified catalog observation
    DERIVED_DATA = "DERIVED_DATA"            # computed from other observables
    SIMULATED_DATA = "SIMULATED_DATA"        # generated by the ASTRA engine
    THEORETICAL_MODEL = "THEORETICAL_MODEL"  # purely mathematical construct
    SPECULATIVE_MODEL = "SPECULATIVE_MODEL"  # requires exotic assumptions


class ScientificConfidence(Enum):
    """Coarse epistemic confidence attaching to a provenance class."""

    OBSERVATIONAL = "OBSERVATIONAL"  # measured / verified
    COMPUTED = "COMPUTED"            # deterministic derivation
    MODEL_DEPENDENT = "MODEL_DEPENDENT"  # valid only under a model


# Documented default confidence per provenance class.
DEFAULT_CONFIDENCE = {
    DataProvenance.REAL_DATA: ScientificConfidence.OBSERVATIONAL,
    DataProvenance.DERIVED_DATA: ScientificConfidence.COMPUTED,
    DataProvenance.SIMULATED_DATA: ScientificConfidence.COMPUTED,
    DataProvenance.THEORETICAL_MODEL: ScientificConfidence.MODEL_DEPENDENT,
    DataProvenance.SPECULATIVE_MODEL: ScientificConfidence.MODEL_DEPENDENT,
}


@dataclass(frozen=True)
class ProvenanceTag:
    """Immutable provenance stamp for a property block."""

    provenance: DataProvenance
    source_label: str = "astra"  # catalog/engine label; free-form, honest

    def __post_init__(self):
        if not isinstance(self.provenance, DataProvenance):
            raise TypeError("provenance must be a DataProvenance member")
        if not isinstance(self.source_label, str) or not self.source_label:
            raise ValueError("source_label must be a non-empty string")

    @property
    def confidence(self) -> ScientificConfidence:
        return DEFAULT_CONFIDENCE[self.provenance]
