"""ASTRA Interaction — integration Protocols (read-only where possible).

Never rebuilds physics/coords/observation/travel.
"""

from __future__ import annotations

from typing import Protocol, Optional, Tuple, Any, Dict


class CoreProvider(Protocol):
    def get_tick(self) -> int: ...
    def get_simulation_time(self) -> float: ...
    def get_event_bus(self) -> Any: ...


class WorldProvider(Protocol):
    def get_hierarchy_node(self, node_id: str) -> Any: ...
    def get_scene_node(self, node_id: str) -> Any: ...
    def get_world_position(self, node_id: str) -> Tuple[float, float, float]: ...
    def query_spatial(self, center: Tuple[float,float,float], radius: float) -> Any: ...


class FrameProvider(Protocol):
    def get_frame(self, frame_id: str) -> Any: ...
    def get_all_frames(self) -> Dict[str, Any]: ...


class SpacecraftProvider(Protocol):
    def start_finite_burn(self, entity_id: str, burn: Any) -> None: ...
    def apply_impulsive(self, entity_id: str, burn: Any) -> None: ...


class MotionProvider(Protocol):
    def step(self, dt: float) -> Any: ...


class TemporalProvider(Protocol):
    def get_simulation_time(self) -> float: ...
    def get_proper_time(self) -> float: ...
    def get_coordinate_time(self) -> float: ...


class ObservationProvider(Protocol):
    def observe(self, history: Any, observer_position: Any, observation_time_s: float, observer: str = ...) -> Any: ...


class ScientificProvider(Protocol):
    def classify(self, *args) -> Any: ...


class TravelProvider(Protocol):
    def can_travel(self, req: Any) -> Tuple[bool, str]: ...
    def initiate(self, req: Any) -> Any: ...
