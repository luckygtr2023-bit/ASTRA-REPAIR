#pragma once
// ASTRA COSMOS — Celestial simulation layer (native mirror of the Python authority).
//
// ARCHITECTURE RULE: the Python package `astra.orbital` is the scientific
// authority. This file mirrors its exact algorithms so the standalone native
// app reproduces the same positions for the same orbital elements:
//   - Kepler elliptic solver: astra/orbital/kepler.py::solve_kepler_elliptic
//     (Newton-Raphson, M wrapped to [-pi, pi], E0 = M for e<0.8 else sign(M)*pi,
//      tol = 1e-12, max_iter = 200 — astra/orbital/constants.py)
//   - E -> true anomaly:   astra/orbital/anomalies.py::eccentric_to_true
//   - Perifocal radius:    astra/orbital/elements.py::elements_to_state
//   - PQW -> IJK rotation: astra/orbital/elements.py::_rotation_pqw_to_ijk
// Fidelity is enforced by tests/kepler_mirror_check.cpp, which compares against
// reference positions generated by the Python engine (see
// scripts/gen_kepler_reference.py) — the two must agree to < 1e-9 relative.
//
// DATA PROVENANCE: planetary elements are the JPL "Keplerian Elements for
// Approximate Positions of the Major Planets" (J2000 epoch) — DATA-DERIVED,
// APPROXIMATE. Propagation = SIMULATED (two-body Kepler, no perturbations).
// Visual scaling in the renderer is a CINEMATIC transform applied at the
// visualization boundary only; scientific state stays in SI (km, s).

#include <array>
#include <string>
#include <vector>

namespace astra::app {

// ---- Units (authoritative, SI-derived) --------------------------------------
inline constexpr double AU_KM = 149597870.7;          // IAU 2012 — REAL
inline constexpr double GM_SUN = 1.32712440018e11;    // km^3/s^2 — DATA-DERIVED
inline constexpr double GM_EARTH = 3.986004418e5;     // km^3/s^2 — DATA-DERIVED
inline constexpr double R_EARTH_KM = 6371.0;          // mean radius — DATA-DERIVED
inline constexpr double DAY_S = 86400.0;
inline constexpr double YEAR_D = 365.25;

using Vec3d = std::array<double, 3>;

// ---- Orbital elements (heliocentric or parent-relative), angles in radians --
struct OrbitalElements {
    double a_km;      // semi-major axis
    double e;         // eccentricity
    double i;         // inclination
    double raan;      // longitude of ascending node (Omega)
    double argp;      // argument of periapsis (omega = varpi - raan)
    double M0;        // mean anomaly at epoch
    double mu;        // gravitational parameter of the central body (km^3/s^2)
    double epoch_s;   // epoch of the elements (sim seconds; J2000 = 0)
};

// Mirror of astra/orbital/kepler.py::solve_kepler_elliptic (Newton-Raphson).
double solve_kepler_elliptic(double mean_anomaly, double e);
// Mirror of astra/orbital/anomalies.py::eccentric_to_true.
double eccentric_to_true(double E, double e);
// Radius + position in the parent frame for time t (mirror of
// astra/orbital/elements.py::elements_to_state + propagation by mean motion).
Vec3d orbital_position(const OrbitalElements& el, double t_s);
// Mean motion n = sqrt(mu / a^3) (rad/s).
double mean_motion(const OrbitalElements& el);
// Velocity in the parent frame (km/s) at time t (mirror of
// astra/orbital/elements.py::elements_to_state velocity branch:
// v_factor = sqrt(mu/p), v_pqw = (-vf sin n, vf (e + cos n), 0) -> IJK).
Vec3d orbital_velocity(const OrbitalElements& el, double t_s);
// Mirror of astra/orbital/elements.py::_rotation_pqw_to_ijk (used by the
// apsis markers to place peri/apo at real positions).
Vec3d rotation_pqw_to_ijk(double i, double raan, double argp, Vec3d v);
// True-anomaly sample of the full orbit (for the orbit-path overlay).
// Returns N evenly spaced (in mean anomaly) parent-frame positions.
std::vector<Vec3d> orbit_polyline(const OrbitalElements& el, double t_s, int n);

// ---- Celestial body definition + solar-system scenario ----------------------
enum class BodyKind { STAR, PLANET, MOON };

struct CelestialBody {
    std::string name;
    BodyKind kind;
    int parent;                 // index into vector, -1 for the primary
    double mass_kg;             // DATA-DERIVED
    double radius_km;           // DATA-DERIVED (mean radius)
    double temperature_k;       // DATA-DERIVED (photosphere/effective); 0 => N/A
    float color[3];             // SIMULATED visual material (not a measurement)
    OrbitalElements elements;   // DATA-DERIVED (JPL approx., J2000), parent-relative
    std::string classification; // REAL / DATA-DERIVED / SIMULATED — UI-vISIBLE
};

// Sun + 8 planets + the Moon, epoch J2000. Elements: JPL approximate table.
std::vector<CelestialBody> make_solar_system();

// Propagate the whole system and return WORLD positions (double, km,
// heliocentric). Moons use parent(world) + relative. Deterministic.
std::vector<Vec3d> propagate_world(const std::vector<CelestialBody>& bodies, double t_s);
// Same for velocities (heliocentric km/s; moons add parent velocity).
std::vector<Vec3d> propagate_world_velocity(const std::vector<CelestialBody>& bodies, double t_s);

// ---- Simulation clock (sim seconds, explicit warp, pausable) ----------------
struct SimClock {
    double sim_time_s = 0.0;  // seconds since epoch (0 == J2000 scenario epoch)
    double warp = 50000.0;    // sim-seconds per real-second (scientific control)
    bool paused = false;
    void advance(double real_dt_s) { if (!paused) sim_time_s += real_dt_s * warp; }
    static double clamp_warp(double w); // [1, 1e8] safety rails
};

} // namespace astra::app
